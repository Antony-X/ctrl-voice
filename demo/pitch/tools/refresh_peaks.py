"""Precompute waveform peaks for every example clip, so the deck can draw real waveforms from file://
(browsers block fetch/decodeAudioData of local files). Run it again whenever an example's audio changes.

Writes pitch/assets/peaks.js: window.CV_PEAKS["examples/clean/before.mp3"] = {dur, rate, p: [0..1 levels]}.
Usage: python refresh_peaks.py
"""
import json
import re
import subprocess
from pathlib import Path

import numpy as np

PITCH = Path(__file__).resolve().parent.parent
RATE = 50                     # levels per second (20 ms windows)
SR = 16000


def decode(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32)


def levels(x):
    hop = SR // RATE
    n = max(1, len(x) // hop)
    frames = x[:n * hop].reshape(n, hop)
    db = 20 * np.log10(np.sqrt((frames ** 2).mean(axis=1)) + 1e-6)
    hi = np.percentile(db, 98)
    lo = hi - 42
    return (np.clip((db - lo) / (hi - lo), 0, 1) ** 1.25).round(3).tolist()


def clip_paths():
    """Audio files referenced by each example.js (src relative to its folder unless it contains a '/')."""
    for js in sorted(list(PITCH.glob("examples/*/example.js")) + list(PITCH.glob("placeholders/*/example.js"))):
        text = js.read_text("utf-8")
        for src in re.findall(r'"src"\s*:\s*"([^"]+)"|\bsrc\s*:\s*[\'"]([^\'"]+)[\'"]', text):
            src = src[0] or src[1]
            rel = (js.parent / src[2:]) if src.startswith("./") else (PITCH / src if "/" in src else js.parent / src)
            yield rel.resolve()


def main():
    out = {}
    for p in dict.fromkeys(clip_paths()):
        if not p.exists():
            print("missing", p)
            continue
        x = decode(p)
        key = p.relative_to(PITCH).as_posix()
        out[key] = {"dur": round(len(x) / SR, 3), "rate": RATE, "bytes": p.stat().st_size, "p": levels(x)}
        print(f"{key}: {out[key]['dur']} s")
    js = ("// Generated by tools/refresh_peaks.py: waveform levels for each example clip (file:// can't decode audio).\n"
          "window.CV_PEAKS = " + json.dumps(out, separators=(",", ":")) + ";\n")
    (PITCH / "assets" / "peaks.js").write_text(js, "utf-8")
    print("wrote assets/peaks.js with", len(out), "clips")


if __name__ == "__main__":
    main()
